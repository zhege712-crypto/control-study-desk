// Glossary is derived from the lessons so the page, the checker and search use one source.
export const zeroTerms = (() => {
  const seen = new Map();
  for (const lesson of zeroLessons) {
    for (const [zh, en, definition] of lesson.terms) {
      if (!seen.has(zh)) seen.set(zh, {zh, en, definition, lesson: lesson.id});
    }
  }
  return [...seen.values()];
})();

export const zeroIds = zeroLessons.map(lesson => lesson.id);
export const zeroLessonById = new Map(zeroLessons.map(lesson => [lesson.id, lesson]));

export function zeroSearchText(lesson) {
  return [lesson.title, lesson.en, lesson.goal, lesson.story, lesson.manual, lesson.gap,
    lesson.table.caption, ...lesson.table.head, ...lesson.table.rows.flat(),
    ...lesson.terms.flat(), lesson.misconception.q, lesson.misconception.a, lesson.check.q, lesson.check.a,
  ].join(' ').toLocaleLowerCase();
}

export function zeroMatches(query) {
  const q = query.trim().toLocaleLowerCase();
  if (!q) return [];
  return zeroLessons.filter(lesson => zeroSearchText(lesson).includes(q));
}
